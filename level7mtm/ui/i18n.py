def set_language(lang: str) -> None:
    _LANG[0] = lang


def language() -> str:
    return _LANG[0]


def tr(text: str) -> str:
    return AR.get(text, text) if _LANG[0] == "ar" else text


def label(d: dict | str | None) -> str:
    if not d:
        return ""
    if isinstance(d, str):
        return d
    return d.get(_LANG[0]) or d.get("en") or d.get("ar") or next(iter(d.values()), "")


