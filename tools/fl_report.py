"""Write docs/reports/FL_EXPERIMENT.md from fl_experiment.json (produced by level7mtm.services.experiment)."""
import json
import sys

r = json.load(open(sys.argv[1], encoding="utf-8"))
out = sys.argv[2]
L = ["# تجربة FL: الطلب نفسه مرتين مع تغيير FL فقط", "",
     "> **تنبيه:** البترون الأساسي المستخدم `thobe-engine-test 0.1.0` نموذج لاختبار المحرك وليس بترون الشياكة. "
     "العلاقات الهندسية لملف GRAFIS لم تُنقل بعد. لذلك تثبت هذه التجربة أن **مسار الربط والحساب والتحقق والنستينج** "
     "يعمل ويتصرف وفق قواعد البترون المستخدم، ولا تثبت أن نتيجة GRAFIS قد أُعيد إنتاجها.", "",
     f"- الطلب الحقيقي: `Order-9-53-1_2.xml`، البند `{r['order']}`. أُعيد إرساله كمراجعة `{r['changed_order']}` "
     f"بعد تغيير FL وحده من {r['fl_cm'][0]} إلى {r['fl_cm'][1]} سم.",
     f"- الفرق في القياسات بعد الاستيراد (مم): `{r['measurement_differences']}`. لم يتغير أي قياس آخر.",
     f"- الفرق في متغيرات البترون بعد قواعد الربط: `{r['variable_differences']}`. القاعدة المستخدمة R001: "
     "FL → القطعة 002 → Basic-Construction 0 → X1 بالقيمة `{M}`.",
     f"- حالة الحساب: {r['generation_status']}، والكمية: {r['quantity']}.", "",
     "## النقاط التي تحركت", "", "| النقطة | الإزاحة (مم) |", "|---|---|"]
for k, v in sorted(r["moved_points"].items()):
    L.append(f"| {k} | dx={v[0]:.3f}، dy={v[1]:.3f} |")
L += ["", "المتوقع حسب قواعد البترون المستخدم: الحافة السفلية تقع عند y = −X1، فتنزل أركانها الأربعة 30 مم، "
      "ولا تتحرك أي نقطة أخرى. **النتيجة مطابقة.**", "", "## القطع والحواف", "",
      "| القطعة | تغير الارتفاع | تغير العرض | الحواف المتغيرة (مم) | النوتشات | النسخ (عادية، معكوسة) |",
      "|---|---|---|---|---|---|"]
for pid, d in r["pieces"].items():
    ch = {e: round(v["delta"], 3) for e, v in d["edges"].items() if abs(v["delta"]) > 1e-9}
    L.append(f"| {pid} | {d['height_delta']:+.3f} | {d['width_delta']:+.3f} | {ch or 'لا شيء (القطعة مطابقة تمامًا)'} "
             f"| لم تتحرك | {d['copies'][0]} ← {d['copies'][1]} |")
L += ["", "خط الجنب يتكون من ثلاث قطع مستقيمة، آخرها مائل من الأرداف إلى أسفل الثوب، لذلك زاد طوله 29.967 مم "
      "وليس 30. الزيادة **متساوية في الأمام والخلف**.", "", "## خطوط التركيب (المراجعة الجديدة)", "",
      "| الزوج | الفرق | النتيجة |", "|---|---|---|"]
for x in r["relations"]["b"]:
    L.append(f"| {x['label']} | {x['diff']:.3f} مم (المتوقع {x['expected_diff']:.1f} ± {x['tolerance']}) | "
             f"{'سليم' if x['ok'] else 'غير مطابق'} |")
L += ["", "فحوص الأبعاد: " + "، ".join(f"`{c['id']}` {'سليم' if c['ok'] else 'يحتاج مراجعة'}"
                                    for c in r["checks"]["b"]) +
      ". الفحص `cap_vs_armhole` كان «يحتاج مراجعة» قبل تغيير FL أيضًا، لأن قاعدة رأس الكم غير معرّفة "
      "في البترون المستخدم.", "", "## النستينج (LEVEL7 Nesting الحالي)", ""]
for k in ("a", "b"):
    n = r["nesting"][k]
    L.append(f"- **{n['sizes'][0]}**: فتح LEVEL7 Nesting الملف وقرأ {n['pieces']} قطع. أقصى فرق في الأبعاد عن "
             f"ناتج MTM = {n['max_geometry_difference_mm']} مم. وُضعت {n['placed']} قطع، وكلها تحمل رقم الطلب "
             f"`{n['placed_sizes'][0]}`. نتيجة التحقق: {'سليم' if n['valid'] else 'غير سليم'}. الكميات: "
             f"`{n['quantities']}`. طول الماركر عند عرض 1450 مم: {n['length_mm']} مم.")
L += ["", "عدد القطع الموضوعة 6: أمام، وخلف، وكم أيمن، وكم أيسر، وقطعتا رقبة. قطع الجبزور والجيب الجانبي وجيب الصدر "
      "مطلوبة بخيارات الطلب، لكنها **غير موجودة في البترون الأساسي**. لذلك سُجلت كموانع للاعتماد "
      "(`plan.piece_missing`)، ولم تُرسل إلى النستينج.", "",
      "الملفات المرسلة ملفات تجريبية `TEST-NOT-FOR-PRODUCTION`، لأن البترون الأساسي غير معتمد. البرنامج يرفض "
      "الإرسال الإنتاجي لهذا البترون.", "",
      "إعادة التشغيل: `pytest tests/test_catalog.py::test_fl_only_experiment` أو "
      "`level7mtm.services.experiment.fl_experiment`."]
open(out, "w", encoding="utf-8").write("\n".join(L) + "\n")
